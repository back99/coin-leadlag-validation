#!/usr/bin/env bash
# 전부 순서대로 돌리고 로그를 남긴다.
#   bash run_all.sh
# 중간에 하나 실패해도 나머지는 계속 돈다.

mkdir -p results
LOG="results/run_$(date +%Y%m%d_%H%M).log"

run_step () {
  echo ""
  echo "################################################################################"
  echo "# $1"
  echo "# 시작: $(date '+%H:%M:%S')"
  echo "################################################################################"
  if python3 "$2"; then
    echo "--- $1 완료 ($(date '+%H:%M:%S'))"
  else
    echo "!!! $1 실패 (계속 진행)"
  fi
}

{
  echo "================================================================================"
  echo " 코인봇 검증 일괄 실행"
  echo " 시작: $(date '+%Y-%m-%d %H:%M:%S')"
  echo "================================================================================"

  # 1. 로직이 안 깨졌는지부터. 네트워크 없이 3초면 끝난다.
  #    이게 실패하면 아래 결과는 볼 필요도 없다.
  run_step "로직 검증 (합성 데이터)" "test_upbit_logic.py"

  # 2. 리드-래그 + 세션 (데이터 최초 수집도 여기서 일어남)
  run_step "리드-래그 + 세션 검증" "upbit_leadlag_check.py"

  # 3. 트리거 비교 (위에서 받은 캐시 재사용)
  run_step "진입 트리거 비교" "upbit_triggers.py"

  # 4. 밤사이 -> 한국 낮 세션 (원래 아이디어의 마지막 조각)
  run_step "세션 로직 검증 (합성 데이터)" "test_overnight_logic.py"
  run_step "밤사이 -> 한국 낮 세션 검증" "overnight_session_check.py"

  echo ""
  echo "================================================================================"
  echo " 전부 완료: $(date '+%Y-%m-%d %H:%M:%S')"
  echo "================================================================================"
  echo ""
  echo "생성된 결과 파일:"
  ls -1 results_*.csv 2>/dev/null | sed 's/^/  /'

} 2>&1 | tee "$LOG"

echo ""
echo "로그 저장됨: $LOG"
